#!/usr/bin/env python3
"""Generates tests/exec/incdec16[_banked].bas: Word and Integer plus or minus one, as Inc/Dec and as `x = x + 1`,
`x = x - 1`, `x = 1 + x` and `x = x + 65535`, at every byte boundary. The _banked program puts the variables above bank 0."""
import os

VALUES = {"Word": [0, 1, 255, 256, 257, 32767, 32768, 65535],
          "Integer": [0, 1, 255, 256, -1, -256, -257, 32767, -32768]}
FORMS = [
    ("Inc({v})", 1), ("Dec({v})", -1),
    ("{v} = {v} + 1", 1), ("{v} = {v} - 1", -1), ("{v} = 1 + {v}", 1), ("{v} = {v} + 65535", -1),
]

def wrap(n, ty):
    n &= 0xFFFF
    return n - 0x10000 if ty == "Integer" and n >= 0x8000 else n

def build(banked):
    decls, body, expect = [], [], []
    if banked:
        decls.append("Dim padarr(300) As Byte")
    r = 0
    for ty, vals in VALUES.items():
        decls.append(f"Dim x{ty} As {ty}")
        for val in vals:
            for form, delta in FORMS:
                r += 1
                decls.append(f"Dim R{r} As {ty}")
                body.append(f"x{ty} = {val}")
                body.append(form.format(v=f"x{ty}"))
                body.append(f"R{r} = x{ty}")
                expect.append(f"T_R{r}={wrap(val + delta, ty)}")
    lines = ["' generated by scripts/gen-incdec-tests.py -- do not edit"]
    for i in range(0, len(expect), 8):
        lines.append("' expect: " + " ".join(expect[i:i + 8]))
    lines += ["Program T", "Device = 18F27Q10", "Clock = 64",
              "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""]
    lines += decls + [""] + body + ["End", ""]
    return "\n".join(lines)

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "exec")
for banked in (False, True):
    with open(os.path.join(out, "incdec16%s.bas" % ("_banked" if banked else "")), "w") as f:
        f.write(build(banked))
