#!/usr/bin/env python3
"""Generates tests/exec/minmax_byte.bas: unsigned Byte `Min` / `Max` over every pair of operands 0..255, with variables,
constants and expressions on either side (the skip-instruction form reads one operand from memory, so an expression or a
Volatile variable takes the spill path).

Usage: gen-minmax-tests.py   (writes the program to stdout)"""

forms = [
    ("MIN", "Min(x, y)", lambda x, y: min(x, y)),
    ("MAX", "Max(x, y)", lambda x, y: max(x, y)),
    ("MINK", "Min(x, 100)", lambda x, y: min(x, 100)),
    ("MAXK", "Max(100, y)", lambda x, y: max(100, y)),
    ("MINL", "Min(x Xor 5, y)", lambda x, y: min(x ^ 5, y)),
    ("MAXR", "Max(x, y Xor 3)", lambda x, y: max(x, y ^ 3)),
    ("MINB", "Min(x Xor 5, y Xor 3)", lambda x, y: min(x ^ 5, y ^ 3)),
    ("MAXV", "Max(v, y)", lambda x, y: max(x, y)),
    ("NEST", "Max(Min(x, y), Min(y, 50))", lambda x, y: max(min(x, y), min(y, 50))),
]
decls = ["Dim i As Word", "Dim j As Word", "Dim x As Byte", "Dim y As Byte", "Volatile Dim v As Byte", "Dim r As Byte"]
body = ["For i = 0 To 255", "x = i", "v = i", "For j = 0 To 255", "y = j"]
exp = []
for name, ex, f in forms:
    decls.append(f"Dim S{name} As LongWord")
    body += [f"r = {ex}", f"S{name} = S{name} + r"]
    exp.append(f"T_S{name}={sum(f(x, y) for x in range(256) for y in range(256))}")
body += ["Next", "Next"]
out = ["' generated by scripts/gen-minmax-tests.py -- do not edit"]
e = exp[:]
while e:
    out.append("' expect: " + " ".join(e[:6]))
    e = e[6:]
out += ["Program T", "Device = 18F27Q10", "Clock = 64", "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""] + decls + [""] + body + ["End"]
print("\n".join(out))
