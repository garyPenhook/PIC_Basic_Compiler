import sys
pad = False
M=lambda n:(1<<(8*n))-1
vals={2:[(0x1234,0xFF0F),(0xFFFF,0x8001)],4:[(0x12345678,0xFF00FF0F),(0xFFFFFFFF,0x80000001)]}
ops=[("+",lambda a,b:a+b),("-",lambda a,b:a-b),("And",lambda a,b:a&b),("Or",lambda a,b:a|b),("Xor",lambda a,b:a^b)]
decls=[];body=[];exp=[];k=0
if pad:
    decls.append("Dim padarr(300) As Byte")
for n,ty in((2,"Word"),(4,"LongWord")):
    decls.append(f"Dim x{n} As {ty}\nDim y{n} As {ty}\nDim b{n} As Byte")
    for X,Y in vals[n]:
        body.append(f"x{n} = {X}\ny{n} = {Y}\nb{n} = 195")
        for name,f in ops:
            for kind in("vv","vk","kv","vb","bv","vkz","kvz"):
                k+=1
                decls.append(f"Dim R{k} As {ty}")
                c=(0x5A00A5|1)&M(n); c2=0x30FF0F&M(n); z=0x100
                e,v={"vv":(f"x{n} {name} y{n}",f(X,Y)),"vk":(f"x{n} {name} {c}",f(X,c)),"kv":(f"{c2} {name} y{n}",f(c2,Y)),
                     "vb":(f"x{n} {name} b{n}",f(X,195)),"bv":(f"b{n} {name} y{n}",f(195,Y)),
                     "vkz":(f"x{n} {name} {z}",f(X,z)),"kvz":(f"{z} {name} y{n}",f(z,Y))}[kind]
                body.append(f"R{k} = {e}")
                exp.append(f"T_R{k}={v&M(n)}")
        body.append(f"x{n} = y{n} - x{n}")
        k+=1; decls.append(f"Dim R{k} As {ty}"); body.append(f"R{k} = x{n}"); exp.append(f"T_R{k}={(Y-X)&M(n)}")
out=["' generated by scripts/gen-direct-tests.py -- do not edit"]
e=exp[:]
while e:
    out.append("' expect: "+" ".join(e[:8])); e=e[8:]
out+=["Program T","Device = 18F27Q10","Clock = 64","Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON",""]+decls+[""]
if pad: body=[f"padarr({i}) = {i}" for i in (0,1,2)]+body
out+=body+["End"]
print("\n".join(out))
