#!/usr/bin/env python3
"""Generates tests/exec/signed_cmp_abs.bas: signed compares against zero and against constants (a sign-bit test, and the
biased last byte of a wide compare) and `Abs` of a ShortInt. A ShortInt form runs over -128..127, an Integer form over a
dense walk around zero plus a strided walk of the whole range; each counts how often it is true, and the expectation is
computed here.

Usage: gen-signed-tests.py   (writes the program to stdout)"""

def s8(v):
    return (v + 128) % 256 - 128

OPS = {"<": lambda a, b: a < b, "<=": lambda a, b: a <= b, ">": lambda a, b: a > b, ">=": lambda a, b: a >= b}
S_VALS = list(range(-128, 128))
I_WALKS = [("-300 To 300", range(-300, 301)), ("-32768 To 32767 Step 61", range(-32768, 32768, 61))]

# (name, variable, BASIC condition, predicate over the variable's value)
forms = []
def add(var, cond, pred):
    forms.append((f"{var.upper()}{len(forms)}", var, cond, pred))

for var, ks in (("s", (0, 5, -5)), ("i", (0, 5, -5, 300, -300))):
    for op, f in OPS.items():
        for k in ks:
            add(var, f"{var} {op} {k}", lambda v, f=f, k=k: f(v, k))
        add(var, f"0 {op} {var}", lambda v, f=f: f(0, v))
for var in ("s", "i"):
    add(var, f"({var} Xor 5) < 0", lambda v: (v ^ 5) < 0)
    add(var, f"({var} Xor 5) >= 0", lambda v: (v ^ 5) >= 0)

abs_forms = [
    ("Abs(s)", lambda s: s8(abs(s))),
    ("Abs(s Xor 5)", lambda s: s8(abs(s ^ 5))),
    ("Abs(Abs(s))", lambda s: s8(abs(s8(abs(s))))),
    ("Abs(s) + 1", lambda s: s8(s8(abs(s)) + 1)),
]

decls = ["Dim j As LongInt", "Dim s As ShortInt", "Dim i As Integer", "Dim t As ShortInt"]
decls += [f"Dim C{n} As Word" for n, *_ in forms]
decls += [f"Dim A{k} As LongInt" for k in range(len(abs_forms))]
exp = []
body = ["For j = -128 To 127", "s = j"]
for n, var, cond, pred in forms:
    if var == "s":
        body += [f"If {cond} Then", f"C{n} = C{n} + 1", "End If"]
        exp.append(f"T_C{n}={sum(1 for v in S_VALS if pred(v))}")
for k, (ex, f) in enumerate(abs_forms):
    body += [f"t = {ex}", f"A{k} = A{k} + t"]
    exp.append(f"T_A{k}={sum(f(v) for v in S_VALS) & 0xFFFFFFFF}")
body.append("Next")
for loop, rng in I_WALKS:
    body += [f"For j = {loop}", "i = j"]
    for n, var, cond, pred in forms:
        if var == "i":
            body += [f"If {cond} Then", f"C{n} = C{n} + 1", "End If"]
    body.append("Next")
for n, var, cond, pred in forms:
    if var == "i":
        exp.append(f"T_C{n}={sum(1 for _, rng in I_WALKS for v in rng if pred(v))}")

out = ["' generated by scripts/gen-signed-tests.py -- do not edit"]
e = exp[:]
while e:
    out.append("' expect: " + " ".join(e[:6]))
    e = e[6:]
out += ["Program T", "Device = 18F27Q10", "Clock = 64", "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""] + decls + [""] + body + ["End"]
print("\n".join(out))
