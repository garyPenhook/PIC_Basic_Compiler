#!/usr/bin/env python3
"""Generates tests/exec/array_plusw_rmw.bas: `arr(i) = 0`, `= 255`, `arr(i) = arr(i) + 1` / `- 1` (and `1 + arr(i)`, `+ 255`)
on a one-byte element picked by a Byte variable, with the neighbouring elements checked for collateral writes, at
the ends of the array and with the 128-byte limit."""
import os

START = [0, 1, 127, 128, 200, 254, 255]
FORMS = [("arr(i) = 0", lambda v: 0), ("arr(i) = 255", lambda v: 255),
         ("arr(i) = arr(i) + 1", lambda v: (v + 1) & 255), ("arr(i) = arr(i) - 1", lambda v: (v - 1) & 255),
         ("arr(i) = 1 + arr(i)", lambda v: (v + 1) & 255), ("arr(i) = arr(i) + 255", lambda v: (v - 1) & 255),
         ("arr(i) = arr(i) - 255", lambda v: (v + 1) & 255)]
N = 128
decls, body, expect = ["Dim i As Byte", f"Dim arr({N}) As Byte"], [], []
n = 0
for idx in (0, 1, 64, 127):
    for form, f in FORMS:
        for v in START:
            n += 1
            decls += [f"Dim R{n} As Byte", f"Dim S{n} As Byte"]
            body += [f"i = {idx}", f"arr({idx}) = {v}"]
            body += [f"arr({max(idx - 1, 0) if idx else 1}) = 77"]
            body += [form, f"R{n} = arr({idx})", f"S{n} = arr({max(idx - 1, 0) if idx else 1})"]
            expect += [f"T_R{n}={f(v)}", f"T_S{n}=77"]
lines = ["' generated by scripts/gen-plusw-rmw-tests.py -- do not edit"]
for k in range(0, len(expect), 8):
    lines.append("' expect: " + " ".join(expect[k:k + 8]))
lines += ["Program T", "Device = 18F27Q10", "Clock = 64",
          "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""]
lines += decls + [""] + body + ["End", ""]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "exec", "array_plusw_rmw.bas")
open(out, "w").write("\n".join(lines))
print(out, n, "cases")
