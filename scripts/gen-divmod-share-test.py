#!/usr/bin/env python3
"""Writes tests/exec/div_mod_share.bas: `/` and `Mod` of the same operands (one shared helper call), including the
shapes that must NOT share (an operand overwritten between the two, a different divisor, Mod first)."""
import os

def tdiv(a, b):  # truncating signed division, remainder takes the dividend's sign
    q = abs(a) // abs(b)
    q = -q if (a < 0) != (b < 0) else q
    return q, a - q * b

# name, type of args, type of result variables, statements (python lambda on x,y,z -> (q, r)), body
R = [
 ("DivMod",   "Word",     "Word",     "{q} = x / y\n    {r} = x Mod y",              lambda x, y, z: divmod(x, y), [(1234, 10), (65535, 7), (7, 9)]),
 ("ModDiv",   "Word",     "Word",     "{r} = x Mod y\n    {q} = x / y",              lambda x, y, z: divmod(x, y), [(1234, 10), (500, 3)]),
 ("OverX",    "Word",     "Word",     "x = x / y\n    {r} = x Mod y\n    {q} = x",   lambda x, y, z: (x // y, (x // y) % y), [(1234, 10), (60000, 7)]),
 ("OverY",    "Word",     "Word",     "y = x / y\n    {r} = x Mod y\n    {q} = y",   lambda x, y, z: (x // y, x % (x // y)), [(1234, 10), (60000, 7)]),
 ("SDivMod",  "Integer",  "Integer",  "{q} = x / y\n    {r} = x Mod y",              lambda x, y, z: tdiv(x, y), [(-1234, 10), (1234, -10), (-32000, -7)]),
 ("BDivMod",  "Byte",     "Byte",     "{q} = x / y\n    {r} = x Mod y",              lambda x, y, z: divmod(x, y), [(200, 7), (255, 16), (9, 2)]),
 ("SBDivMod", "ShortInt", "ShortInt", "{q} = x / y\n    {r} = x Mod y",              lambda x, y, z: tdiv(x, y), [(-100, 7), (100, -7)]),
 ("LDivMod",  "LongWord", "LongWord", "{q} = x / y\n    {r} = x Mod y",              lambda x, y, z: divmod(x, y), [(1234567, 1000), (4000000000, 70001)]),
 ("LSDivMod", "LongInt",  "LongInt",  "{q} = x / y\n    {r} = x Mod y",              lambda x, y, z: tdiv(x, y), [(-1234567, 1000), (1234567, -71)]),
 ("Both",     "Word",     "Word",     "{q} = x / y + x Mod y\n    {r} = 0",         lambda x, y, z: (x // y + x % y, 0), [(1234, 10), (50000, 3)]),
 ("TwoDiv",   "Word",     "Word",     "{q} = x / y\n    {r} = x Mod z",              lambda x, y, z: (x // y, x % z), [(1234, 10, 1000), (65000, 9, 100)]),
]
out, exp, decl, calls = [], [], [], []
glob = set()
for name, at, rt, body, f, argsets in R:
    for ty in sorted({rt}):
        pass
    body = body.replace("q", f"{name}q").replace("r", f"{name}r") if False else body
    glob.add((name, rt))
    out.append(f"Sub {name}(ByVal x As {at}, ByVal y As {at}" + (", ByVal z As Word" if name == "TwoDiv" else "") + f")\n    {body.format(q=name+'q', r=name+'r')}\nEnd Sub\n")
    for k, a in enumerate(argsets):
        a = tuple(a) + (1,) * (3 - len(a))
        qv, rv = f(*a)
        decl.append((f"{name}Q{k}", rt)); decl.append((f"{name}R{k}", rt))
        call = ", ".join(str(v) for v in a[: (3 if name == "TwoDiv" else 2)])
        qn, rn = {"Word": "q", "Integer": "q"}.get(rt, "q"), "r"
        calls.append(f"{name}({call})\n{name}Q{k} = {name}q\n{name}R{k} = {name}r")
        mask = (1 << {"Word": 16, "Integer": 16, "Byte": 8, "ShortInt": 8, "LongWord": 32, "LongInt": 32}[rt]) - 1
        exp.append(f"T_{name.upper()}Q{k}={qv & mask} T_{name.upper()}R{k}={rv & mask}")
hdr = ["' expect: " + " ".join(exp[i:i + 6]) if i == 0 else "' expect: " + " ".join(exp[i:i + 6]) for i in range(0, len(exp), 6)]
s = "\n".join(hdr) + "\n"
s += """' Generated by scripts/gen-divmod-share-test.py. `/` and `Mod` of the same operands share one helper call (peephole
' pass_div_share). Every routine is called with different run-time values so nothing folds. ModDiv (Mod first), OverX and
' OverY (an operand is overwritten between the two statements) and TwoDiv (a different second divisor) must keep two calls.
Program T
Device = 18F27Q10
Clock = 64
Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON

"""
for n, t in decl:
    s += f"Dim {n} As {t}\n"
for n, t_ in sorted(glob):
    s += f"Dim {n}q As {t_}\nDim {n}r As {t_}\n"
s += "\n"
s += "\n".join(out) + "\n" + "\n".join(calls) + "\nEnd\n"
open(os.path.join(os.path.dirname(__file__), "..", "tests", "exec", "div_mod_share.bas"), "w").write(s)
