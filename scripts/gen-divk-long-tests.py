#!/usr/bin/env python3
"""Writes tests/exec/div_const_long.bas: LongWord `/` and `Mod` by byte constants (the __divk4 helper)."""
import os
ks = [3, 5, 7, 10, 13, 100, 200, 255]
vals = [0, 1, 9, 10, 255, 256, 65535, 65536, 1234567, 16777215, 16777216, 2147483647, 2147483648, 4000000000, 4294967295]
M = 0xFFFFFFFF
exp = []
for k in ks:
    exp.append(f"T_SQ{k}={sum(v // k for v in vals) & M} T_SR{k}={sum(v % k for v in vals) & M}")
s = ""
for i in range(0, len(exp), 4):
    s += "' expect: " + " ".join(exp[i:i + 4]) + "\n"
s += """' Generated by scripts/gen-divk-long-tests.py. LongWord / and Mod by byte constants: sums of the quotients and of the
' remainders over a table of edge values (run-time indices, so nothing folds).
Program T
Device = 18F27Q10
Clock = 64
Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON

"""
s += f"Dim vals({len(vals)}) As LongWord\n"
for k in ks:
    s += f"Dim SQ{k} As LongWord\nDim SR{k} As LongWord\n"
s += "Dim i As Byte\n\n"
for k in ks:
    s += f"Sub D{k}(ByVal x As LongWord)\n    SQ{k} = SQ{k} + x / {k}\n    SR{k} = SR{k} + x Mod {k}\nEnd Sub\n\n"
for j, v in enumerate(vals):
    s += f"vals({j}) = {v}\n"
s += f"For i = 0 To {len(vals) - 1}\n"
for k in ks:
    s += f"    D{k}(vals(i))\n"
s += "Next\nEnd\n"
open(os.path.join(os.path.dirname(__file__), "..", "tests", "exec", "div_const_long.bas"), "w").write(s)
