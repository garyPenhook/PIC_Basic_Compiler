#!/usr/bin/env python3
"""Generates tests/exec/byte_ops.bas: Byte `a - b`, `K - b`, `a >> 1`, and narrowed Byte targets of `-a`, `Not a`,
`a + b` evaluated wider (B1, B6, B7), over edge values."""
import os

V = [0, 1, 2, 5, 127, 128, 129, 200, 254, 255]
decls, body, expect = ["Dim a As Byte", "Dim b As Byte", "Dim w As Word"], [], []
n = 0
def case(setup, expr, f):
    global n
    n += 1
    decls.append(f"Dim R{n} As Byte")
    body.extend(setup + [f"R{n} = {expr}"])
    expect.append(f"T_R{n}={f & 255}")
for x in V:
    for y in V:
        s = [f"a = {x}", f"b = {y}"]
        case(s, "a - b", x - y)
        case(s, "200 - b", 200 - y)
        case(s, "a - 7", x - 7)
        case(s, "(a + 1) - b", (x + 1) - y)
        case(s, "a - (b + 1)", x - (y + 1))
    s = [f"a = {x}"]
    case(s, "a >> 1", x >> 1)
    case(s, "-a", -x)
    case(s, "Not a", ~x)
    case(s, "(0 - a) + 3", -x + 3)
    case(s + ["w = 1000"], "w - a", 1000 - x)
lines = ["' generated by scripts/gen-byteops-tests.py -- do not edit"]
for k in range(0, len(expect), 8):
    lines.append("' expect: " + " ".join(expect[k:k + 8]))
lines += ["Program T", "Device = 18F27Q10", "Clock = 64",
          "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""]
lines += decls + [""] + body + ["End", ""]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "exec", "byte_ops.bas")
open(out, "w").write("\n".join(lines))
print(out, n, "cases")
