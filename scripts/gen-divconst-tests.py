#!/usr/bin/env python3
"""Generates tests/exec/div_const_byte.bas: unsigned Byte `/ K` and `Mod K` by constants, every dividend 0..255 per divisor.
Each divisor sums the quotients and remainders (from a variable and from an expression) into Words; divisors without a
single-byte reciprocal (7, 11, 255 ...) check that the helper fallback still agrees.

Usage: gen-divconst-tests.py   (writes the program to stdout)"""

ks = list(range(3, 41)) + [63, 99, 100, 101, 127, 128, 129, 170, 200, 254, 255]
decls = ["Dim i As Word", "Dim x As Byte", "Dim q As Byte", "Dim r As Byte"]
body, exp = [], []
for k in ks:
    decls += [f"Dim Q{k} As Word", f"Dim M{k} As Word", f"Dim E{k} As Word"]
    body += [
        "For i = 0 To 255",
        "x = i",
        f"q = x / {k}",
        f"r = x Mod {k}",
        f"Q{k} = Q{k} + q",
        f"M{k} = M{k} + r",
        f"E{k} = E{k} + (x Xor 3) / {k} + (x Xor 3) Mod {k}",
        "Next",
    ]
    exp += [f"T_Q{k}={sum(n // k for n in range(256))}", f"T_M{k}={sum(n % k for n in range(256))}",
            f"T_E{k}={sum((n ^ 3) // k + (n ^ 3) % k for n in range(256))}"]
out = ["' generated by scripts/gen-divconst-tests.py -- do not edit"]
e = exp[:]
while e:
    out.append("' expect: " + " ".join(e[:8]))
    e = e[8:]
out += ["Program T", "Device = 18F27Q10", "Clock = 64", "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""] + decls + [""] + body + ["End"]
print("\n".join(out))
