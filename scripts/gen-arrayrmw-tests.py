#!/usr/bin/env python3
"""Generates tests/exec/array_rmw.bas: element stores, loads and `arr(i) = arr(i) op operand` on Byte, Word and
LongWord arrays picked by a Byte variable (PLUSW0 path up to 128 bytes, FSR0 add up to 256 bytes, address build
beyond), with the neighbouring element checked for collateral writes."""
import os

ARR = [("ab", "Byte", 1, 20), ("aw", "Word", 2, 20), ("al", "LongWord", 4, 16), ("ax", "Word", 2, 100), ("ay", "Byte", 1, 200), ("az", "Byte", 1, 256), ("aq", "Word", 2, 150)]
EDGE = {1: [0, 1, 127, 255], 2: [0, 1, 255, 256, 32768, 65535], 4: [0, 1, 65535, 65536, 2**31, 2**32 - 1]}
OPS = [("+", lambda a, b: a + b), ("-", lambda a, b: a - b), ("And", lambda a, b: a & b),
       ("Or", lambda a, b: a | b), ("Xor", lambda a, b: a ^ b)]
decls, body, expect = ["Dim i As Byte", "Dim bad As Byte"], [], []
n = 0
def case(arr, ty, sz, idx, base, stmts, expr):
    global n
    n += 1
    mask = (1 << (8 * sz)) - 1
    nb = idx - 1 if idx else 1
    decls.append(f"Dim R{n} As {ty}")
    body.extend([f"i = {idx}", f"{arr}({idx}) = {base}", f"{arr}({nb}) = {mask - 2}"] + stmts)
    body.extend([f"R{n} = {arr}({idx})", f"If {arr}({nb}) <> {mask - 2} Then", "bad = bad + 1", "End If"])
    expect.append(f"T_R{n}={expr & mask}")
for arr, ty, sz, cnt in ARR:
    decls.append(f"Dim {arr}({cnt}) As {ty}")
    decls.append(f"Dim v{arr} As {ty}")
    E = EDGE[sz]
    mask = (1 << (8 * sz)) - 1
    for idx in (0, cnt // 2, cnt - 1):
        for base in (E[1], E[-2]):
            case(arr, ty, sz, idx, base, [f"v{arr} = {E[-2]}", f"{arr}(i) = v{arr}"], E[-2])
            for k in (0, E[-1], 1234 & mask):
                case(arr, ty, sz, idx, base, [f"{arr}(i) = {k}"], k)
            for op, f in OPS:
                case(arr, ty, sz, idx, base, [f"v{arr} = {E[-2]}", f"{arr}(i) = {arr}(i) {op} v{arr}"], f(base, E[-2]))
                for k in (3, E[-1]):
                    case(arr, ty, sz, idx, base, [f"{arr}(i) = {arr}(i) {op} {k}"], f(base, k))
expect.append("T_BAD=0")
lines = ["' generated by scripts/gen-arrayrmw-tests.py -- do not edit"]
for k in range(0, len(expect), 8):
    lines.append("' expect: " + " ".join(expect[k:k + 8]))
lines += ["Program T", "Device = 18F27Q10", "Clock = 64",
          "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""]
lines += decls + [""] + body + ["End", ""]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "exec", "array_rmw.bas")
open(out, "w").write("\n".join(lines))
print(out, n, "cases")
