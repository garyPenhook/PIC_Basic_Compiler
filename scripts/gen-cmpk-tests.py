#!/usr/bin/env python3
"""Generates tests/exec/cmp_const_pack.bas: unsigned Word and LongWord ordered compares against constants on either
side (including the largest value of the type), and a Word built from two Bytes with `hi * 256 + lo`, `(hi << 8) Or lo`
and constants."""
import os

OPS = {"<": lambda a, b: a < b, "<=": lambda a, b: a <= b, ">": lambda a, b: a > b, ">=": lambda a, b: a >= b}
W = ([0, 1, 255, 256, 999, 1000, 1001, 0x7FFF, 0x8000, 0xFFFE, 0xFFFF], [0, 1, 999, 1000, 1001, 255, 256, 65534, 65535])
L = ([0, 1, 255, 65535, 65536, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFE, 0xFFFFFFFF], [0, 1, 65535, 65536, 0x123456, 0xFFFFFFFE, 0xFFFFFFFF])

decls, body, expect = ["Dim hi As Byte", "Dim lo As Byte"], [], []
n = 0

def new(ty, cond=None, val=None):
    global n
    n += 1
    decls.append(f"Dim R{n} As {ty}")
    return n

for ty, (xs, ks) in (("Word", W), ("LongWord", L)):
    decls.append(f"Dim x{ty} As {ty}")
    for x in xs:
        body.append(f"x{ty} = {x}")
        for k in ks:
            for op, f in OPS.items():
                for text, val in ((f"x{ty} {op} {k}", f(x, k)), (f"{k} {op} x{ty}", f(k, x))):
                    r = new("Byte")
                    body.extend([f"R{r} = 0", f"If {text} Then", f"R{r} = 1", "End If"])
                    expect.append(f"T_R{r}={int(val)}")

for h in (0, 1, 0x80, 0xFF, 0xA5):
    for l in (0, 1, 0x7F, 0xFF, 0x5A):
        body.extend([f"hi = {h}", f"lo = {l}"])
        v = h * 256 + l
        for form in ("hi * 256 + lo", "lo + hi * 256", "256 * hi + lo", "(hi << 8) Or lo", "lo Or (hi << 8)", "(hi << 8) + lo"):
            r = new("Word")
            body.append(f"R{r} = {form}")
            expect.append(f"T_R{r}={v}")
        r = new("Word")
        body.append(f"R{r} = hi * 256 + 90")
        expect.append(f"T_R{r}={h * 256 + 90}")

lines = ["' generated by scripts/gen-cmpk-tests.py -- do not edit"]
for i in range(0, len(expect), 8):
    lines.append("' expect: " + " ".join(expect[i:i + 8]))
lines += ["Program T", "Device = 18F27Q10", "Clock = 64",
          "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""]
lines += decls + [""] + body + ["End", ""]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "exec", "cmp_const_pack.bas")
open(out, "w").write("\n".join(lines))
print(out, n, "checks")
