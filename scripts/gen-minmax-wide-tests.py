#!/usr/bin/env python3
"""Generates tests/exec/minmax_wide.bas: `Min`, `Max` and `Abs` on signed Byte and on 16- and 32-bit operands (compare
and conditional copy, in-place negate). Every pair of a list of edge values is run through variable, constant, expression,
Volatile and nested forms; each form's results are summed and the expectation is computed here.

Usage: gen-minmax-wide-tests.py   (writes the program to stdout)"""

def wrap(v, bits, signed):
    v &= (1 << bits) - 1
    return v - (1 << bits) if signed and v >> (bits - 1) else v

# (BASIC type, bits, signed, values)
types = [
    ("ShortInt", 8, True, [-128, -127, -64, -2, -1, 0, 1, 2, 63, 126, 127]),
    ("Integer", 16, True, [-32768, -32767, -1000, -257, -256, -255, -129, -128, -127, -2, -1, 0, 1, 2, 127, 128, 255, 256, 257, 1000, 32766, 32767]),
    ("Word", 16, False, [0, 1, 2, 127, 128, 255, 256, 257, 1000, 32767, 32768, 32769, 40000, 65534, 65535]),
    ("LongInt", 32, True, [-2147483648, -2147483647, -70000, -65537, -65536, -65535, -257, -256, -129, -128, -2, -1, 0, 1, 2, 127, 128, 255, 256, 65535, 65536, 65537, 70000, 2147483646, 2147483647]),
    ("LongWord", 32, False, [0, 1, 2, 255, 256, 65535, 65536, 65537, 70000, 2147483647, 2147483648, 2147483649, 4294967294, 4294967295]),
]

out = ["' generated by scripts/gen-minmax-wide-tests.py -- do not edit"]
decls, body, exp = [], [], []
for t, bits, signed, vals in types:
    p = t[:2].upper() + t[-1].upper() if False else t.upper()
    n = len(vals)
    k = vals[len(vals) // 3]
    acc = "LongInt" if bits < 32 else t
    abits, asigned = (32, True) if bits < 32 else (bits, signed)
    decls += [f"Dim ax{t}({n}) As {t}", f"Dim x{t} As {t}", f"Dim y{t} As {t}", f"Volatile Dim v{t} As {t}", f"Dim r{t} As {t}"]
    forms = [
        ("MIN", "Min(x, y)", lambda x, y: min(x, y)),
        ("MAX", "Max(x, y)", lambda x, y: max(x, y)),
        ("MINK", f"Min(x, {k})", lambda x, y: min(x, k)),
        ("MAXK", f"Max({k}, y)", lambda x, y: max(k, y)),
        ("MINL", "Min(x Xor 5, y)", lambda x, y: min(wrap(x ^ 5, bits, signed), y)),
        ("MAXR", "Max(x, y Xor 3)", lambda x, y: max(x, wrap(y ^ 3, bits, signed))),
        ("MINB", "Min(x Xor 5, y Xor 3)", lambda x, y: min(wrap(x ^ 5, bits, signed), wrap(y ^ 3, bits, signed))),
        ("MAXV", "Max(v, y)", lambda x, y: max(x, y)),
        ("MINV", "Min(x, v)", lambda x, y: min(x, x)),
        ("NEST", f"Max(Min(x, y), Min(y, {k}))", lambda x, y: max(min(x, y), min(y, k))),
    ]
    if signed:
        forms += [
            ("ABS", "Abs(x)", lambda x, y: wrap(abs(x), bits, True)),
            ("ABSE", "Abs(x Xor 5)", lambda x, y: wrap(abs(wrap(x ^ 5, bits, True)), bits, True)),
            ("ABSM", "Abs(Min(x, y))", lambda x, y: wrap(abs(min(x, y)), bits, True)),
            ("ABSV", "Abs(v)", lambda x, y: wrap(abs(x), bits, True)),
        ]
    for i, v in enumerate(vals):
        body.append(f"ax{t}({i}) = {v}" if v != -2147483648 else f"ax{t}({i}) = -2147483647 - 1")
    for name, ex, f in forms:
        decls.append(f"Dim S{t}{name} As {acc}")
        total = 0
        for a in vals:
            for b in vals:
                total += f(a, b)
        exp.append(f"T_S{t.upper()}{name}={wrap(total, abits, asigned)}")
    body += [f"For i = 0 To {n - 1}", f"x{t} = ax{t}(i)", f"v{t} = ax{t}(i)", f"For j = 0 To {n - 1}", f"y{t} = ax{t}(j)"]
    for name, ex, f in forms:
        e = ex.replace("x", f"x{t}").replace("y", f"y{t}").replace("v", f"v{t}") if False else None
        import re
        e = re.sub(r"\b([xyv])\b", lambda m: m.group(1) + t, ex)
        e = e.replace("Min(", "Min(").replace("Max(", "Max(")
        body += [f"r{t} = {e}", f"S{t}{name} = S{t}{name} + r{t}"]
    body += ["Next", "Next"]

e = exp[:]
while e:
    out.append("' expect: " + " ".join(e[:5]))
    e = e[5:]
out += ["Program T", "Device = 18F27Q10", "Clock = 64", "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", "", "Dim i As Byte", "Dim j As Byte"] + decls + [""] + body + ["End"]
print("\n".join(out))
