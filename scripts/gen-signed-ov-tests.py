#!/usr/bin/env python3
"""Generates tests/exec/signed_ov_cmp.bas: signed ShortInt, Integer and LongInt ordered compares (< <= > >=) between
two variables, a variable and a constant, a constant and a variable, and a constant and a computed value (`x + z`, z
zero at run time: either side, so the constant-left fold of a computed operand is covered), over operands at the edges of each range,
so the subtract overflows (32767 against -1, -128 against 1). Each true compare adds a weight unique to its operand
pair to a sum per width and operator, and the sums are checked against Python's answers."""
import pathlib

WIDTHS = [
    ("ShortInt", "S", 8, [-128, -127, -2, -1, 0, 1, 126, 127]),
    ("Integer", "I", 16, [-32768, -32767, -129, -1, 0, 1, 32766, 32767]),
    ("LongInt", "L", 32, [-2147483648, -2147483647, -65536, -1, 0, 1, 2147483646, 2147483647]),
]
OPS = [("LT", "<", lambda a, b: a < b), ("LE", "<=", lambda a, b: a <= b), ("GT", ">", lambda a, b: a > b),
       ("GE", ">=", lambda a, b: a >= b)]
N = 8


def lit(v):
    # The most negative value as an expression, so the literal itself stays in range.
    return f"({v + 1} - 1)" if v in (-2147483648,) else str(v)


def main():
    exp, body, dims = {}, [], []
    for ty, t, _, vals in WIDTHS:
        dims.append(f"Dim v{t}({N}) As {ty} = ({', '.join(lit(v) for v in vals)})")
        dims.append(f"Dim x{t}, y{t}, z{t} As {ty}")
        for name, _, _ in OPS:
            for form in ("VV", "VK", "KV", "EK", "KE"):
                dims.append(f"Dim {t}{name}{form} As LongWord")
                exp[f"T_{t}{name}{form}"] = 0
        body += ["For i = 0 To 7", f"    x{t} = v{t}(i)", f"    z{t} = v{t}(4)", "    For j = 0 To 7", f"        y{t} = v{t}(j)",
                 "        w = i * 8 + j + 1"]
        for name, op, f in OPS:
            body += [f"        If x{t} {op} y{t} Then", f"            {t}{name}VV = {t}{name}VV + w", "        End If"]
        body += ["    Next"]
        # Every constant on either side, with a weight per (constant, value) pair.
        for k, kv in enumerate(vals):
            body += [f"    w = i + {k * 8 + 1}"]
            for name, op, f in OPS:
                body += [f"    If x{t} {op} {lit(kv)} Then", f"        {t}{name}VK = {t}{name}VK + w", "    End If",
                         f"    If {lit(kv)} {op} x{t} Then", f"        {t}{name}KV = {t}{name}KV + w", "    End If",
                         f"    If x{t} + z{t} {op} {lit(kv)} Then", f"        {t}{name}EK = {t}{name}EK + w", "    End If",
                         f"    If {lit(kv)} {op} x{t} + z{t} Then", f"        {t}{name}KE = {t}{name}KE + w", "    End If"]
        body += ["Next"]
        for i, a in enumerate(vals):
            for j, b in enumerate(vals):
                for name, _, f in OPS:
                    if f(a, b):
                        exp[f"T_{t}{name}VV"] += i * 8 + j + 1
            for k, kv in enumerate(vals):
                for name, _, f in OPS:
                    if f(a, kv):
                        exp[f"T_{t}{name}VK"] += i + k * 8 + 1
                        exp[f"T_{t}{name}EK"] += i + k * 8 + 1
                    if f(kv, a):
                        exp[f"T_{t}{name}KV"] += i + k * 8 + 1
                        exp[f"T_{t}{name}KE"] += i + k * 8 + 1
    items = [f"{k}={v}" for k, v in exp.items()]
    head = ["' generated by scripts/gen-signed-ov-tests.py -- do not edit"]
    head += ["' expect: " + " ".join(items[i:i + 6]) for i in range(0, len(items), 6)]
    src = head + ["Program T", "Device = 18F27Q10", "Clock = 64",
                  "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", "",
                  "Dim i, j As Byte", "Dim w As Byte"] + dims + [""] + body + [""]
    out = pathlib.Path(__file__).resolve().parent.parent / "tests/exec/signed_ov_cmp.bas"
    out.write_text("\n".join(src))
    print(out)


if __name__ == "__main__":
    main()
