#!/usr/bin/env python3
"""Generates tests/exec/shift_direct_{word,long}[_banked].bas: constant shifts and power-of-two multiplies of Word,
Integer, LongWord and LongInt variables, in place (`x = x << k`) and into another variable (`r = x << k`).

Usage: gen-shift-tests.py word|long [pad]   (writes the program to stdout)"""
import sys

which = sys.argv[1]
pad = len(sys.argv) > 2
types = {"word": [(2, "Word", False), (2, "Integer", True)], "long": [(4, "LongWord", False), (4, "LongInt", True)]}[which]
vals = {2: [0x8765, 0x1234], 4: [0x87654321, 0x12345678]}
ks = {2: range(1, 16), 4: [1, 2, 3, 4, 5, 7, 8, 9, 12, 15, 16, 17, 23, 24, 25, 31]}
mul_ks = {2: [1, 3, 8, 15], 4: [1, 3, 8, 16, 24]}


def wrap(v, n, signed):
    v &= (1 << (8 * n)) - 1
    return v - (1 << (8 * n)) if signed and v >> (8 * n - 1) else v


decls, body, exp = [], [], []
if pad:
    decls.append("Dim padarr(300) As Byte")
r = 0
for n, ty, signed in types:
    decls.append(f"Dim x{ty} As {ty}")
    for val in vals[n]:
        sv = wrap(val, n, signed)
        for k in ks[n]:
            for op, name in (("<<", "shl"), (">>", "shr")):
                res = wrap(sv << k, n, signed) if op == "<<" else sv >> k
                for form in ("place", "other"):
                    r += 1
                    decls.append(f"Dim R{r} As {ty}")
                    body.append(f"x{ty} = {sv}")
                    if form == "place":
                        body.append(f"x{ty} = x{ty} {op} {k}")
                        body.append(f"R{r} = x{ty}")
                    else:
                        body.append(f"R{r} = x{ty} {op} {k}")
                    exp.append(f"T_R{r}={res}")
        for k in mul_ks[n]:
            for form in ("place", "other", "swapped"):
                r += 1
                decls.append(f"Dim R{r} As {ty}")
                body.append(f"x{ty} = {sv}")
                if form == "place":
                    body.append(f"x{ty} = x{ty} * {1 << k}")
                    body.append(f"R{r} = x{ty}")
                elif form == "other":
                    body.append(f"R{r} = x{ty} * {1 << k}")
                else:
                    body.append(f"R{r} = {1 << k} * x{ty}")
                exp.append(f"T_R{r}={wrap(sv << k, n, signed)}")
out = ["' generated by scripts/gen-shift-tests.py -- do not edit"]
e = exp[:]
while e:
    out.append("' expect: " + " ".join(e[:8]))
    e = e[8:]
out += ["Program T", "Device = 18F27Q10", "Clock = 64", "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""] + decls + [""]
if pad:
    body = [f"padarr({i}) = {i}" for i in (0, 1, 2)] + body
out += body + ["End"]
print("\n".join(out))
