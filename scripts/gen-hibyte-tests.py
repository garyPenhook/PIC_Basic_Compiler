#!/usr/bin/env python3
"""Generates tests/exec/hibyte_cmp.bas: unsigned 16-bit compares against multiples of 256 (high byte only), constants
on either side, and `= 0` / `<> 0` on Word and LongWord."""
import os

OPS = {"<": lambda a, b: a < b, "<=": lambda a, b: a <= b, ">": lambda a, b: a > b, ">=": lambda a, b: a >= b}
XS = [0, 1, 255, 256, 257, 511, 512, 513, 0x7FFF, 0x8000, 0xFEFF, 0xFF00, 0xFFFF]
CONSTS = [256, 255, 512, 511, 0xFF00, 0xFEFF, 0xFFFF, 1000]
LONGS = [0, 1, 0x100, 0x10000, 0x1000000, 0x80000000]

decls, body, expect = ["Dim xw As Word", "Dim xl As LongWord"], [], []
n = 0

def test(cond, val):
    global n
    n += 1
    decls.append(f"Dim R{n} As Byte")
    body.extend([f"R{n} = 0", f"If {cond} Then", f"R{n} = 1", "End If"])
    expect.append(f"T_R{n}={int(val)}")

for x in XS:
    body.append(f"xw = {x}")
    for c in CONSTS:
        for op, f in OPS.items():
            test(f"xw {op} {c}", f(x, c))
            test(f"{c} {op} xw", f(c, x))
    test("xw = 0", x == 0)
    test("xw <> 0", x != 0)
for x in LONGS:
    body.append(f"xl = {x}")
    test("xl = 0", x == 0)
    test("xl <> 0", x != 0)

lines = ["' generated by scripts/gen-hibyte-tests.py -- do not edit"]
for i in range(0, len(expect), 8):
    lines.append("' expect: " + " ".join(expect[i:i + 8]))
lines += ["Program T", "Device = 18F27Q10", "Clock = 64",
          "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""]
lines += decls + [""] + body + ["End", ""]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "exec", "hibyte_cmp.bas")
open(out, "w").write("\n".join(lines))
print(out, n, "checks")
