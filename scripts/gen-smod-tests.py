#!/usr/bin/env python3
"""Generates tests/exec/smod_pow2.bas: signed `x Mod 2^k` (k = 1..8) on ShortInt, Integer and LongInt over the edge values
and a strided walk, in a variable and an expression form. The remainder takes the sign of `x` (truncating division).

Usage: gen-smod-tests.py   (writes the program to stdout)"""
import math

def wrap(v, bits):
    v &= (1 << bits) - 1
    return v - (1 << bits) if v >> (bits - 1) else v

def tmod(x, d):
    return int(math.copysign(abs(x) % d, x)) if x else 0

types = [("ShortInt", 8, list(range(-128, 128))),
         ("Integer", 16, [-32768, -32767, -1234, -257, -256, -255, -129, -128, -127, -3, -2, -1, 0, 1, 2, 3, 127, 128, 255, 256, 257, 1235, 32766, 32767] + list(range(-32768, 32768, 997))),
         ("LongInt", 32, [-2147483648, -2147483647, -70000, -65537, -65536, -65535, -257, -256, -255, -1, 0, 1, 255, 256, 257, 65535, 65536, 65537, 70000, 2147483646, 2147483647] + list(range(-2147483648, 2147483647, 99999989)))]
decls, body, exp = [], [], []
for t, bits, vals in types:
    decls += [f"Dim a{t}({len(vals)}) As {t}", f"Dim x{t} As {t}", f"Dim r{t} As {t}"]
    for i, v in enumerate(vals):
        body.append(f"a{t}({i}) = {v}" if v != -2**31 else f"a{t}({i}) = -2147483647 - 1")
    for k in range(1, 9):
        d = 1 << k
        for form, ex, f in (("V", f"x{t} Mod {d}", lambda x: tmod(x, d)), ("E", f"(x{t} Xor 1) Mod {d}", lambda x: tmod(wrap(x ^ 1, bits), d))):
            name = f"S{t.upper()}{form}{k}"
            decls.append(f"Dim {name} As LongInt")
            body += [f"For i = 0 To {len(vals) - 1}", f"x{t} = a{t}(i)", f"r{t} = {ex}", f"{name} = {name} + r{t}", "Next"]
            exp.append(f"T_{name}={wrap(sum(f(v) for v in vals), 32)}")
out = ["' generated by scripts/gen-smod-tests.py -- do not edit"]
e = exp[:]
while e:
    out.append("' expect: " + " ".join(e[:6]))
    e = e[6:]
out += ["Program T", "Device = 18F27Q10", "Clock = 64", "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", "", "Dim i As Word"] + decls + [""] + body + ["End"]
print("\n".join(out))
