#!/usr/bin/env python3
"""Generates tests/exec/div_const_word.bas: unsigned Word `/ K` and `Mod K` by constants. Each divisor runs a spread of dividends
(every 257th value from each of several offsets, plus the edges 0, 1, K-1, K, K+1, 65535) and sums the quotients and remainders into
LongWords, from a variable and from an expression. Divisors without a 16-bit reciprocal check that the helper fallback agrees.

Usage: gen-divconst-word-tests.py   (writes the program to stdout)"""

ks = [3, 5, 6, 9, 10, 12, 13, 25, 60, 99, 100, 101, 255, 257, 1000, 1023, 1025, 10000, 32767, 40000, 65535]
xs = sorted(set(range(0, 65536, 257)) | {1, 2, 3, 65534, 65535} | {v for k in ks for v in (k - 1, k, k + 1, 2 * k, 2 * k - 1) if 0 <= v < 65536})
decls = ["Dim i As Word", "Dim x As Word", "Dim q As Word", "Dim r As Word", "Dim p As Word", "Dim Z As Word"]
body, exp = [], []
for k in ks:
    decls += [f"Dim Q{k} As LongWord", f"Dim M{k} As LongWord", f"Dim E{k} As LongWord"]
    body += [f"Q{k} = 0", f"M{k} = 0", f"E{k} = 0"]
    body += [f"For p = 0 To {len(xs) - 1}", "x = Tab(p)", f"q = x / {k}", f"r = x Mod {k}",
             f"Q{k} = Q{k} + q", f"M{k} = M{k} + r",
             f"E{k} = E{k} + (x Xor 3) / {k} + (x Xor 3) Mod {k}", "Next"]
    exp += [f"T_Q{k}={sum(n // k for n in xs)}", f"T_M{k}={sum(n % k for n in xs)}",
            f"T_E{k}={sum((n ^ 3) // k + (n ^ 3) % k for n in xs)}"]
out = ["' generated by scripts/gen-divconst-word-tests.py -- do not edit"]
e = exp[:]
while e:
    out.append("' expect: " + " ".join(e[:6]))
    e = e[6:]
out += ["#option Optimize = Speed", "Program T", "Device = 18F27Q10", "Clock = 64", "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON", ""]
out += [f"Const Tab({len(xs)}) As Word = (" + ", ".join(map(str, xs)) + ")"] + decls + [""] + body + ["End"]
print("\n".join(out))
