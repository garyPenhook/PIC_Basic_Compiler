#!/usr/bin/env python3
"""Generates tests/exec/arith_*.bas: every operator at every width, on run-time operands.

Expected values are computed here, independently of the compiler, with the language rules:
integer arithmetic wraps at the target width (LANGUAGE.md 5.3), division and Mod truncate
toward zero, Mod takes the dividend's sign, >> is arithmetic for signed types.
"""
import random, os

random.seed(18)
OUT = os.path.join(os.path.dirname(__file__), "../tests/exec")

TYPES = {  # name: (bits, signed)
    "Byte": (8, False), "ShortInt": (8, True), "Word": (16, False),
    "Integer": (16, True), "LongWord": (32, False), "LongInt": (32, True),
}

def wrap(v, bits, signed):
    v &= (1 << bits) - 1
    if signed and v >= 1 << (bits - 1):
        v -= 1 << bits
    return v

def tdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q

def values(bits, signed):
    lo, hi = (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if signed else (0, (1 << bits) - 1)
    edge = {lo, hi, 0, 1, 2, 3, 7, 100, hi // 2, hi // 2 + 1}
    if signed:
        edge |= {-1, -2, -3, -100, lo + 1}
    edge = {e for e in edge if lo <= e <= hi}
    rnd = {random.randint(lo, hi) for _ in range(6)}
    return sorted(edge | rnd)

def lit(v):
    return str(v)

for tname, (bits, signed) in TYPES.items():
    vals = values(bits, signed)
    pairs = [(random.choice(vals), random.choice(vals)) for _ in range(14)]
    pairs += [(vals[0], vals[-1]), (vals[-1], vals[0]), (vals[-1], 1 if True else 0)]
    decl, body, expect = [], [], []
    n = 0
    def new(ty):
        global n
        n += 1
        name = f"r{n}"
        decl.append(f"Dim {name} As {ty}")
        return name
    decl.append(f"Dim a As {tname}")
    decl.append(f"Dim b As {tname}")
    decl.append("Dim k As Byte")
    for (va, vb) in pairs:
        body.append(f"a = {lit(va)} : b = {lit(vb)}")
        for sym, f in [("+", lambda x, y: x + y), ("-", lambda x, y: x - y), ("*", lambda x, y: x * y),
                       ("And", lambda x, y: x & y), ("Or", lambda x, y: x | y), ("Xor", lambda x, y: x ^ y)]:
            r = new(tname)
            body.append(f"{r} = a {sym} b")
            expect.append((r, wrap(f(va, vb), bits, signed)))
        if vb != 0:
            for sym, f in [("/", tdiv), ("Mod", lambda x, y: x - tdiv(x, y) * y)]:
                r = new(tname)
                body.append(f"{r} = a {sym} b")
                expect.append((r, wrap(f(va, vb), bits, signed)))
        for sym, f in [("<", lambda x, y: x < y), (">", lambda x, y: x > y), ("<=", lambda x, y: x <= y),
                       (">=", lambda x, y: x >= y), ("=", lambda x, y: x == y), ("<>", lambda x, y: x != y)]:
            r = new("Boolean")
            body.append(f"{r} = a {sym} b")
            expect.append((r, int(f(va, vb))))
        r = new(tname)
        body.append(f"{r} = -a" if signed else f"{r} = Not a")
        expect.append((r, wrap(-va if signed else ~va, bits, signed)))
        for kk in sorted({0, 1, 3, 4, 7, bits - 1} | {random.randint(0, bits - 1)}):
            body.append(f"k = {kk}")
            for sym in ("<<", ">>"):
                r = new(tname)
                body.append(f"{r} = a {sym} k")
                v = wrap(va << kk, bits, signed) if sym == "<<" else va >> kk
                expect.append((r, wrap(v, bits, signed)))
                r = new(tname)
                body.append(f"{r} = a {sym} {kk}")
                expect.append((r, wrap(v, bits, signed)))
    prog = "T"
    lines = [f"' generated by scripts/gen-arith-tests.py -- do not edit",
             f"Program {prog}", "Device = 18F27Q10", "Clock = 64",
             "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON"]
    lines += decl + body
    # expectations in chunks so each line stays readable
    exp = [f"{prog}_{r.upper()}={v}" for r, v in expect]
    for i in range(0, len(exp), 8):
        lines.insert(1 + i // 8, "' expect: " + " ".join(exp[i:i + 8]))
    with open(os.path.join(OUT, f"arith_{tname.lower()}.bas"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(tname, len(expect), "checks")

# ---- multiplication by constants, and Word * Byte (hardware multiplier paths) ----
decl, body, expect = [], [], []
n = 0
def newr(ty):
    global n
    n += 1
    decl.append(f"Dim r{n} As {ty}")
    return f"r{n}"
for tname in ("Word", "Integer", "LongWord", "LongInt"):
    bits, signed = TYPES[tname]
    var = f"v{tname}"
    decl.append(f"Dim {var} As {tname}")
    consts = {1, 2, 3, 10, 100, 255, 256, 257, 1000, 4096, 0x0A00, 0x1234, 0x7FFF, 0x10001, 0x123456, 1000000}
    consts |= {1 << (bits - 1), (1 << bits) - 1, 0x80, 0xFF00, 0x8001}
    if signed:
        consts |= {-1, -3, -100, -256, -(1 << (bits - 1))}
    consts = sorted(c for c in consts if -(1 << (bits - 1)) <= c < (1 << bits) and (signed or c >= 0)
                    and (not signed or c < (1 << (bits - 1))))
    for va in values(bits, signed)[::2]:
        body.append(f"{var} = {va}")
        for c in consts:
            r = newr(tname)
            body.append(f"{r} = {var} * {c}")
            expect.append((r, wrap(va * c, bits, signed)))
            if c in (10, 257, 0x1234):
                r = newr(tname)
                body.append(f"{r} = {c} * {var}")
                expect.append((r, wrap(va * c, bits, signed)))
decl += ["Dim bb As Byte", "Dim ww As Word", "Dim lw As LongWord"]
for vb in (0, 1, 7, 200, 255):
    for vw in (0, 1, 255, 256, 1000, 0x1234, 0xFFFF):
        body.append(f"bb = {vb} : ww = {vw}")
        r = newr("Word")
        body.append(f"{r} = ww * bb")
        expect.append((r, wrap(vw * vb, 16, False)))
        r = newr("LongWord")
        body.append(f"{r} = ww * bb")
        expect.append((r, vw * vb))
        r = newr("Word")
        body.append(f"{r} = bb * bb")
        expect.append((r, vb * vb))
lines = ["' generated by scripts/gen-arith-tests.py -- do not edit",
         "Program T", "Device = 18F27Q10", "Clock = 64",
         "Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON"] + decl + body
exp = [f"T_{r.upper()}={v}" for r, v in expect]
for i in range(0, len(exp), 8):
    lines.insert(1 + i // 8, "' expect: " + " ".join(exp[i:i + 8]))
with open(os.path.join(OUT, "arith_mulconst.bas"), "w") as f:
    f.write("\n".join(lines) + "\n")
print("mulconst", len(expect), "checks")
