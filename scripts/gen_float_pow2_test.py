#!/usr/bin/env python3
"""Writes tests/exec/float_pow2.bas: the Float code the compiler specialises (x * 2^k and x / 2^k as an
exponent step, a compare with zero, a Byte/Word converted to Float, a conversion call moved ahead of the other
operand) against the library's general routines on the same operand bit patterns.

Usage: gen_float_pow2_test.py > tests/exec/float_pow2.bas
"""
import random
from decimal import Decimal, getcontext

getcontext().prec = 400
random.seed(2024)

specials = [0, 0x80000000, 1, 0x007FFFFF, 0x80000001, 0x00800000, 0x00800001, 0x01000000, 0x01800000, 0x7F7FFFFF, 0xFF7FFFFF,
            0x7F000000, 0x7E800000, 0x7F800000, 0xFF800000, 0x7FC00000, 0xFFC00001, 0x7F800001, 0x3F800000, 0xBF800000, 0x40000000,
            0x3F000000, 0x7F000001, 0x00FFFFFF, 0x80800000]
for e in (1, 2, 3, 4, 126, 127, 128, 129, 252, 253, 254):
    for _ in range(3):
        specials.append(random.getrandbits(1) << 31 | e << 23 | random.getrandbits(23))
while len(specials) < 96:
    specials.append(random.getrandbits(32))


def lit(k):
    d = Decimal(2) ** k
    s = format(d, "f")
    return s if "." in s else s + ".0"


def bits(k):
    return (k + 127) << 23


KS = [1, -1, 2, -2, 0, 127, -126, 100, -100, 7, -7, 20]
bytes_ = [0, 1, 2, 3, 127, 128, 255, 254, 200, 7, 85, 170]
words = [0, 1, 255, 256, 257, 4095, 4096, 32767, 32768, 65535, 65534, 40000, 1000, 511, 12345]

out = []
w = out.append
w("' expect: FP_BAD=0 FP_FIRST=0")
w("' Generated by scripts/gen_float_pow2_test.py. FP_FIRST is 0, or the check (see Miss calls) * 256 + index + 1 of the first mismatch.")
w("Program Fp")
w("Device = 18F27Q10")
w("Clock = 64")
w("Config FEXTOSC = OFF, RSTOSC = HFINTOSC_64MHZ, WDTE = OFF, LVP = ON")
w('Include "floatlib"')
w("Const XV(%d) As LongWord = (%s)" % (len(specials), ", ".join(str(v) for v in specials)))
w("Const WV(%d) As Word = (%s)" % (len(words), ", ".join(str(v) for v in words)))
w("Dim bad As Word")
w("Dim first As Word")
w("Dim i As Byte")
w("Dim b As Byte")
w("Dim v As Word")
w("Dim x As Float")
w("Dim xw As x.AsLongWord")
w("Dim h As Float")
w("Dim hw As h.AsLongWord")
w("Dim t As Float")
w("Dim tw As t.AsLongWord")
w("Dim z As Float")
w("Dim b1 As Boolean")
w("Dim b2 As Boolean")
w("Sub Miss(ByVal op As Byte, ByVal idx As Byte)")
w("    Inc(bad)")
w("    If first = 0 Then")
w("        first = Word(op) * 256 + idx + 1")
w("    End If")
w("End Sub")
w("z = 0")
w("For i = 0 To %d" % (len(specials) - 1))
w("    xw = XV(i)")
chk = 0
for k in KS:
    chk += 1
    w("    h = x * %s" % lit(k))
    w("    If hw <> FloatLib.FMul(XV(i), %d) Then Miss(%d, i)" % (bits(k), chk))
    chk += 1
    w("    h = %s * x" % lit(k))
    w("    If hw <> FloatLib.FMul(%d, XV(i)) Then Miss(%d, i)" % (bits(k), chk))
    chk += 1
    w("    h = x / %s" % lit(k))
    w("    If hw <> FloatLib.FDiv(XV(i), %d) Then Miss(%d, i)" % (bits(k), chk))
    chk += 1
    w("    h = x * %s + 0.0" % lit(k))
    w("    If hw <> FloatLib.FAdd(FloatLib.FMul(XV(i), %d), 0) Then Miss(%d, i)" % (bits(k), chk))
rel = [("=", "="), ("<>", "<>"), ("<", "<"), ("<=", "<="), (">", ">"), (">=", ">=")]
for op, _ in rel:
    chk += 1
    w("    b1 = x %s 0.0" % op)
    w("    b2 = x %s z" % op)
    w("    If b1 <> b2 Then Miss(%d, i)" % chk)
    chk += 1
    w("    b1 = 0.0 %s x" % op)
    w("    b2 = z %s x" % op)
    w("    If b1 <> b2 Then Miss(%d, i)" % chk)
    chk += 1
    w("    b1 = x %s -0.0" % op)
    w("    b2 = x %s z" % op)
    w("    If b1 <> b2 Then Miss(%d, i)" % chk)
w("    If x > 0.0 Then")
w("        b1 = True")
w("    Else")
w("        b1 = False")
w("    End If")
w("    b2 = x > z")
w("    If b1 <> b2 Then Miss(%d, i)" % (chk + 1))
chk += 1
# a Byte or Word source, then an operation whose operands are in either order
w("    b = i * 37 + 11")
w("    v = WV(i And 7) + i")
for op, fn in (("+", "FAdd"), ("*", "FMul")):
    for var in ("b", "v"):
        chk += 1
        w("    t = %s" % var)
        w("    h = x %s %s" % (op, var))
        w("    If hw <> FloatLib.%s(XV(i), tw) Then Miss(%d, i)" % (fn, chk))
        chk += 1
        w("    h = %s %s x" % (var, op))
        w("    If hw <> FloatLib.%s(tw, XV(i)) Then Miss(%d, i)" % (fn, chk))
for var in ("b", "v"):
    chk += 1
    w("    t = %s" % var)
    w("    h = x - %s" % var)
    w("    If hw <> FloatLib.FAdd(XV(i), tw Xor $80000000) Then Miss(%d, i)" % chk)
    chk += 1
    w("    h = %s - x" % var)
    w("    If hw <> FloatLib.FAdd(tw, XV(i) Xor $80000000) Then Miss(%d, i)" % chk)
w("    b = 0")
w("    v = 0")
for op, fn in (("+", "FAdd"), ("*", "FMul")):
    for var in ("b", "v"):
        chk += 1
        w("    t = %s" % var)
        w("    h = x %s %s" % (op, var))
        w("    If hw <> FloatLib.%s(XV(i), tw) Then Miss(%d, i)" % (fn, chk))
        chk += 1
        w("    h = %s %s x" % (var, op))
        w("    If hw <> FloatLib.%s(tw, XV(i)) Then Miss(%d, i)" % (fn, chk))
for var in ("b", "v"):
    chk += 1
    w("    t = %s" % var)
    w("    h = x - %s" % var)
    w("    If hw <> FloatLib.FAdd(XV(i), tw Xor $80000000) Then Miss(%d, i)" % chk)
    chk += 1
    w("    h = %s - x" % var)
    w("    If hw <> FloatLib.FAdd(tw, XV(i) Xor $80000000) Then Miss(%d, i)" % chk)
w("Next")
# Byte and Word to Float over their ranges
w("For i = 0 To 255")
w("    t = i")
w("    If tw <> FloatLib.FFromULong(i) Then Miss(%d, i)" % (chk + 1))
w("Next")
chk += 1
w("For i = 0 To %d" % (len(words) - 1))
w("    v = WV(i)")
w("    t = v")
w("    If tw <> FloatLib.FFromULong(v) Then Miss(%d, i)" % (chk + 1))
w("    v = v + i * 257")
w("    t = v")
w("    If tw <> FloatLib.FFromULong(v) Then Miss(%d, i)" % (chk + 2))
w("Next")
import re
lines = []
for ln in out:
    m = re.match(r"^(\s*)If (.*) Then (Miss\(.*\))$", ln)
    if m:
        lines += [f"{m[1]}If {m[2]} Then", f"{m[1]}    {m[3]}", f"{m[1]}End If"]
    else:
        lines.append(ln)
print("\n".join(lines))
