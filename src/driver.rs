//! Back-end driver: builds the code generator's target description from the device file, runs
//! pic-as, and prints the size report.

use crate::codegen::{Generated, Target};
use crate::ir::{CArg, ExportSig, ExternSig, Program};
use devdesc::Device;
use std::path::{Path, PathBuf};
use std::process::Command;

pub fn target_of(dev: &Device) -> Target {
    let mut ram: Vec<(u32, u32)> = Vec::new();
    for g in dev.memory.data.gpr.iter().filter(|g| !g.system) {
        let start = g.start.max(dev.memory.data.access_ram.end);
        if start >= g.end {
            continue;
        }
        match ram.last_mut() {
            Some(l) if l.1 == start => l.1 = g.end,
            _ => ram.push((start, g.end)),
        }
    }
    let sfr: std::collections::HashMap<String, u32> = dev.sfr.iter().map(|s| (s.name.clone(), s.addr)).collect();
    let hw_context = sfr.contains_key("SHADCON");
    let data_top = dev.memory.data.gpr.iter().map(|g| g.end).chain(dev.memory.data.sfr.iter().map(|r| r.end)).max().unwrap_or(0);
    let acc = &dev.memory.data.access_sfr;
    Target {
        ram,
        access: (dev.memory.data.access_ram.start, dev.memory.data.access_ram.end),
        access_sfr: (acc.start, acc.end),
        sfr,
        hw_context,
        data_top,
        hw_stack: if dev.memory.hw_stack > 0 { dev.memory.hw_stack } else { crate::codegen::HW_STACK_LEVELS },
        opt: true,
        keep_vars: false,
        debug_files: Vec::new(),
    }
}

/// The newest installed pic-as, or the one named by `BASIL_PICAS`.
pub fn find_pic_as() -> Option<PathBuf> {
    if let Ok(p) = std::env::var("BASIL_PICAS") {
        return Some(PathBuf::from(p));
    }
    let root = Path::new("/opt/microchip/xc8");
    let mut found: Vec<PathBuf> = std::fs::read_dir(root).ok()?.filter_map(|e| e.ok()).map(|e| e.path().join("pic-as/bin/pic-as")).filter(|p| p.is_file()).collect();
    found.sort();
    found.pop()
}

/// The device pack's `xc8` folder (`-mdfp`).
pub fn find_dfp(dev: &Device) -> Option<PathBuf> {
    let home = std::env::var("HOME").ok()?;
    let p = Path::new(&home).join(".mchp_packs/Microchip").join(&dev.device.pack).join(&dev.device.pack_version).join("xc8");
    p.is_dir().then_some(p)
}

/// The C compiler driver (`xc8-cc`) of the same XC8 install as `pic_as`, or the one named by `BASIL_XC8CC`.
pub fn find_xc8_cc(pic_as: &Path) -> Option<PathBuf> {
    if let Ok(p) = std::env::var("BASIL_XC8CC") {
        return Some(PathBuf::from(p));
    }
    // <xc8>/pic-as/bin/pic-as sits beside <xc8>/bin/xc8-cc.
    let p = pic_as.parent()?.parent()?.parent()?.join("bin/xc8-cc");
    p.is_file().then_some(p)
}

/// The C file the program is linked with besides its `CFile`s. It holds
///
/// * `basil_io`, a byte array the generated code writes the arguments of a C call to and reads the result from;
/// * one `basil_w_<name>` per `Extern` routine, which reads the arguments from `basil_io`, calls the C function and
///   writes its result back; a wrapper is plain C, so XC8 passes the arguments as it likes at any optimisation level;
/// * `main`, which the XC8 start-up code calls: it enters the generated code (`basil_entry`, never returns) and then
///   calls every wrapper. Those calls never run; they put the wrappers, and through them the C functions, in the
///   call graph XC8 builds from `main`, which is what keeps them and gives them frames.
///
/// XC8 compiles all the code at once, so `basil_io` is volatile (it cannot know the generated code writes it).
pub fn c_stub(externs: &[ExternSig], exports: &[ExportSig]) -> String {
    let bytes = |v: Vec<u32>| v.into_iter().max().unwrap_or(0).max(1);
    let sizes = |params: &[CArg], ret: &Option<CArg>| [params.iter().map(|p| u32::from(p.bytes())).sum(), ret.as_ref().map_or(0, |r| u32::from(r.bytes()))];
    let n = bytes(externs.iter().flat_map(|e| sizes(&e.params, &e.ret)).chain(exports.iter().flat_map(|e| sizes(&e.params, &e.ret))).collect());
    let mut s = format!("/* generated by basil */\nextern void basil_entry(void);\nvolatile unsigned char basil_io[{n}];\n");
    // A structure is only named here (the C file defines it); declared first so the name is not local to a prototype.
    let mut tags: Vec<&str> = externs.iter().flat_map(|e| e.params.iter()).chain(exports.iter().flat_map(|e| e.params.iter())).filter_map(|a| if let CArg::Ptr(to) = a { to.rsplit_once("struct ").map(|t| t.1) } else { None }).collect();
    tags.sort_unstable();
    tags.dedup();
    for t in tags {
        s.push_str(&format!("struct {t};\n"));
    }
    for e in externs {
        let mut at = 0;
        let mut args = Vec::new();
        let mut protos = Vec::new();
        for a in &e.params {
            let t = a.c_type();
            // A pointer travels as a 16-bit address.
            let arg = if let CArg::Ptr(_) = a { format!("({t})*(volatile unsigned int *)(basil_io + {at})") } else { format!("*(volatile {t} *)(basil_io + {at})") };
            args.push(arg);
            protos.push(t);
            at += u32::from(a.bytes());
        }
        let call = format!("{}({})", e.name, args.join(", "));
        let ret = e.ret.as_ref().map_or("void".to_string(), CArg::c_type);
        s.push_str(&format!("{ret} {}({});\n", e.name, if protos.is_empty() { "void".into() } else { protos.join(", ") }));
        match &e.ret {
            Some(r) => s.push_str(&format!("void basil_w_{}(void) {{ *(volatile {t} *)basil_io = {call}; }}\n", e.name, t = r.c_type())),
            None => s.push_str(&format!("void basil_w_{}(void) {{ {call}; }}\n", e.name)),
        }
    }
    // An exported routine is C code that moves its arguments into `basil_io` and calls the assembly thunk.
    for e in exports {
        let mut at = 0;
        let mut decl = Vec::new();
        let mut put = String::new();
        for (i, a) in e.params.iter().enumerate() {
            let t = a.c_type();
            decl.push(format!("{t} a{i}"));
            let v = if let CArg::Ptr(_) = a { format!("(unsigned int)a{i}") } else { format!("a{i}") };
            let st = if let CArg::Ptr(_) = a { "unsigned int".to_string() } else { t };
            put.push_str(&format!(" *(volatile {st} *)(basil_io + {at}) = {v};", st = st));
            at += u32::from(a.bytes());
        }
        let ret = e.ret.as_ref().map_or("void".to_string(), CArg::c_type);
        let get = e.ret.as_ref().map_or(String::new(), |r| format!(" return *(volatile {} *)basil_io;", r.c_type()));
        s.push_str(&format!("extern void {}(void);\n{ret} {}({}) {{{put} {}();{get} }}\n", e.entry, e.name, if decl.is_empty() { "void".into() } else { decl.join(", ") }, e.entry));
    }
    s.push_str("void main(void) {\n    basil_entry();\n");
    for e in externs {
        s.push_str(&format!("    basil_w_{}();\n", e.name));
    }
    s.push_str("}\n");
    s
}

/// Links the generated assembly with the program's C files through `xc8-cc`. The data RAM the
/// program allocated itself (`reserved`, start and end exclusive) is kept free of C data.
pub fn run_xc8_cc(xc8: &Path, dev: &Device, asm: &Path, stub: &Path, cfiles: &[PathBuf], reserved: &[(u32, u32)], hex: &Path, map: &Path) -> Result<AsmRun, String> {
    let dfp = find_dfp(dev).ok_or_else(|| format!("device pack {} {} not found under ~/.mchp_packs", dev.device.pack, dev.device.pack_version))?;
    let cpu = dev.device.name.strip_prefix("PIC").unwrap_or(&dev.device.name).to_string();
    let mut cmd = Command::new(xc8);
    cmd.arg(format!("-mcpu={cpu}")).arg(format!("-mdfp={}", dfp.display())).arg("-Os").arg("-Wno-1388");
    for (a, e) in reserved {
        cmd.arg(format!("-mreserve=ram@0x{a:X}:0x{:X}", e - 1));
    }
    let out = cmd
        .arg(format!("-Wl,-Map={}", map.display()))
        .arg("-o")
        .arg(hex)
        .arg(asm)
        .arg(stub)
        .args(cfiles)
        .output()
        .map_err(|e| format!("cannot run {}: {e}", xc8.display()))?;
    let mut text = String::from_utf8_lossy(&out.stdout).into_owned();
    text.push_str(&String::from_utf8_lossy(&out.stderr));
    Ok(AsmRun { ok: out.status.success(), output: text })
}

pub struct AsmRun {
    pub ok: bool,
    pub output: String,
}

pub fn run_pic_as(pic_as: &Path, dev: &Device, asm: &Path, hex: &Path, map: &Path) -> Result<AsmRun, String> {
    let dfp = find_dfp(dev).ok_or_else(|| format!("device pack {} {} not found under ~/.mchp_packs", dev.device.pack, dev.device.pack_version))?;
    let cpu = dev.device.name.strip_prefix("PIC").unwrap_or(&dev.device.name).to_string();
    let out = Command::new(pic_as)
        .arg(format!("-mcpu={cpu}"))
        .arg(format!("-mdfp={}", dfp.display()))
        // The configuration words keep the bits the pack leaves out of `implemented` at 1 (lower.rs), which pic-as
        // reports as "truncated by" although it writes them to the hex as given.
        .arg("-Wno-1388")
        .arg(format!("-Wl,-Map={}", map.display()))
        .arg("-o")
        .arg(hex)
        .arg(asm)
        .output()
        .map_err(|e| format!("cannot run {}: {e}", pic_as.display()))?;
    let mut text = String::from_utf8_lossy(&out.stdout).into_owned();
    text.push_str(&String::from_utf8_lossy(&out.stderr));
    Ok(AsmRun { ok: out.status.success(), output: text })
}

/// Data RAM bytes the program places (variables, temporaries, scratch registers).
pub fn ram_used(g: &Generated) -> u32 {
    g.objs.iter().enumerate().filter(|(i, _)| g.layout.addr.get(*i).copied().flatten().is_some()).map(|(_, o)| o.bytes).sum()
}

/// One bar line: `label [####....]  used / size unit (pct)`.
fn usage_line(label: &str, used: u32, size: u32, unit: &str, color: bool) -> String {
    const W: usize = 24;
    let pct = if size == 0 { 0.0 } else { used as f64 * 100.0 / size as f64 };
    let filled = ((pct / 100.0 * W as f64).ceil() as usize).min(W).max(usize::from(used > 0));
    let bar = format!("{}{}", "█".repeat(filled), "░".repeat(W - filled));
    let (on, off) = match (color, pct) {
        (false, _) => ("", ""),
        (true, p) if p >= 90.0 => ("\x1b[31m", "\x1b[0m"),
        (true, p) if p >= 75.0 => ("\x1b[33m", "\x1b[0m"),
        (true, _) => ("\x1b[32m", "\x1b[0m"),
    };
    format!("  {label:<6}{on}{bar}{off}  {used:>6} / {size} {unit}  ({pct:.1}%)\n")
}

/// The flash and RAM use against what the chosen device has, printed after every successful build.
pub fn usage_summary(dev: &Device, g: &Generated, color: bool) -> String {
    let flash_bytes = dev.memory.program.size;
    let mut s = format!("{}:\n", dev.device.name);
    s.push_str(&usage_line("Flash", g.out.words * 2, flash_bytes, "bytes", color));
    s.push_str(&usage_line("RAM", ram_used(g), dev.memory.data.usable_gpr, "bytes", color));
    s
}

pub fn report(p: &Program, g: &Generated) -> String {
    let mut s = String::new();
    s.push_str(&format!("Program: {} words ({} bytes)\n", g.out.words, g.out.words * 2));
    for (n, w) in &g.out.func_words {
        s.push_str(&format!("  {:6} words  {n}\n", w));
    }
    let nv = p.vars.len();
    let mut total = 0;
    s.push_str("Data RAM:\n");
    let mut rows: Vec<(u32, String, u32)> = Vec::new();
    for (i, o) in g.objs.iter().enumerate() {
        if let Some(a) = g.layout.addr.get(i).copied().flatten() {
            let name = if i < nv { format!("{} ({})", o.name, p.vars[i].name) } else { o.name.clone() };
            rows.push((a, name, o.bytes));
            total += o.bytes;
        }
    }
    rows.sort();
    for (a, n, b) in rows {
        s.push_str(&format!("  0x{a:03X}  {b:3}  {n}\n"));
    }
    s.push_str(&format!("  total {total} bytes\n"));
    s
}
